def build_vscode(palette):
    files = {}
    for name, variant in palette["variants"].items():
        c, dark = variant["colors"], variant["appearance"] == "dark"
        theme = {
            "$schema": "vscode://schemas/color-theme",
            "name": title(name),
            "type": "dark" if dark else "light",
            "semanticHighlighting": True,
            "colors": vscode_workbench(c, dark),
            "tokenColors": vscode_tokens(c),
            "semanticTokenColors": vscode_semantic(c),
        }
        files[f"themes/karazuri-{name}-color-theme.json"] = json_text(theme)
    return files


