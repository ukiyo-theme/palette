T3_THEMES = {
    # theme id: (display name, dark variant, light variant)
    "ukiyo": ("Ukiyo", "umi", "kami"),
    "ukiyo-yoru": ("Ukiyo Yoru", "yoru", "kami"),
}


def build_t3code(palette):
    variants = palette["variants"]
    files = {}
    for theme_id, (name, dark_name, light_name) in T3_THEMES.items():
        theme = {"name": name, "version": 1, "appearance": "dark"}
        theme.update(t3_roles(variants[dark_name]["colors"], True))
        # A variant is a flat role -> color map, so canvas and accent sit beside the other roles.
        light = t3_roles(variants[light_name]["colors"], False)
        theme["variants"] = {"light": {"canvas": light["canvas"], "accent": light["accent"], **light["colors"]}}
        files[f"themes/{theme_id}.json"] = json_text(theme)
    return files


TARGETS = {
    "nvim": build_nvim,
    "vscode": build_vscode,
    "zed": build_zed,
    "t3code": build_t3code,
}


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("target", choices=sorted(TARGETS))
    parser.add_argument("--out", type=Path, help="root of the port's repo; files are written under it")
    parser.add_argument("--palette", type=Path, default=ROOT / "palette.json")
    args = parser.parse_args()

    files = TARGETS[args.target](json.loads(args.palette.read_text()))
    for path, content in files.items():
        if args.out:
            dest = args.out / path
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(content)
            print(f"wrote {dest}", file=sys.stderr)
        else:
            sys.stdout.write(f"==> {path} <==\n{content}\n")


if __name__ == "__main__":
    main()
