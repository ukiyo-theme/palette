"""Generate editor and terminal color files from palette.json.

Usage:
  python3 scripts/build.py <target> [--out PATH]

Targets:
  nvim    Lua palette table for ukiyo-theme/nvim (lua/ukiyo/palette.lua)

Without --out the result is printed to stdout.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = "Generated by ukiyo-theme/palette (scripts/build.py) from palette.json. Do not edit by hand."


def camel(variant, role):
    """umi + bg_p2 -> umiBgP2, the key style the Neovim plugin uses."""
    return variant + "".join(part[:1].upper() + part[1:] for part in role.split("_"))


def build_nvim(palette):
    lines = [f"-- {HEADER}", "", "---@class PaletteColors", "return {"]
    for name, variant in palette["variants"].items():
        lines.append(f"    -- {name}: {variant['description']}")
        for role, color in variant["colors"].items():
            lines.append(f'    {camel(name, role)} = "{color}",')
        lines.append("")
    lines[-1] = "}"
    return "\n".join(lines) + "\n"


TARGETS = {
    "nvim": build_nvim,
}


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("target", choices=sorted(TARGETS))
    parser.add_argument("--out", type=Path, help="file to write instead of stdout")
    parser.add_argument("--palette", type=Path, default=ROOT / "palette.json")
    args = parser.parse_args()

    output = TARGETS[args.target](json.loads(args.palette.read_text()))
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(output)
        print(f"wrote {args.out}", file=sys.stderr)
    else:
        sys.stdout.write(output)


if __name__ == "__main__":
    main()
