def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("target", choices=sorted(TARGETS))
    parser.add_argument("--out", type=Path, help="root of the port's repo; files are written under it")
    parser.add_argument("--palette", type=Path, default=ROOT / "palette.json")
    args = parser.parse_args()

    files = TARGETS[args.target](json.loads(args.palette.read_text()))
    for path, content in files.items():
        if args.out:
            dest = args.out / path
            dest.parent.mkdir(parents=True, exist_ok=True)
            if isinstance(content, bytes):
                dest.write_bytes(content)
            else:
                dest.write_text(content)
            print(f"wrote {dest}", file=sys.stderr)
        elif isinstance(content, bytes):
            sys.stdout.write(f"==> {path} ({len(content)} bytes, use --out to write) <==\n")
        else:
            sys.stdout.write(f"==> {path} <==\n{content}\n")


if __name__ == "__main__":
    main()
