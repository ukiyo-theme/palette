# Color helpers -----------------------------------------------------------

def rgb(color):
    return [int(color[i:i + 2], 16) for i in (1, 3, 5)]


def mix(a, b, t):
    """Blend t of color b into color a."""
    return "#" + "".join(f"{round(x + (y - x) * t):02X}" for x, y in zip(rgb(a), rgb(b)))


def alpha(color, a):
    return f"{color}{round(a * 255):02X}"


def title(name):
    return f"Ukiyo {name.capitalize()}"


def json_text(data):
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


# ANSI colors in order 0-15, matching the Neovim port's terminal colors.
ANSI_NAMES = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white",
              "bright_black", "bright_red", "bright_green", "bright_yellow",
              "bright_blue", "bright_magenta", "bright_cyan", "bright_white"]
ANSI_DARK = ["bg0", "builtin", "string", "operator", "func", "keyword", "type", "fg_dim",
             "comment", "error", "git_add", "field", "info", "param", "special", "fg"]
ANSI_LIGHT = ["fg", "builtin", "string", "operator", "func", "keyword", "type", "bg_p2",
              "comment", "error", "git_add", "field", "info", "param", "special", "bg0"]


def ansi(variant):
    roles = ANSI_DARK if variant["appearance"] == "dark" else ANSI_LIGHT
    return {name: variant["colors"][role] for name, role in zip(ANSI_NAMES, roles)}


def on_accent(c, dark):
    """Text color to put on top of an accent-colored background."""
    return c["bg0"] if dark else c["bg"]


# Neovim ------------------------------------------------------------------

def camel(variant, role):
    """umi + bg_p2 -> umiBgP2, the key style the Neovim plugin uses."""
    return variant + "".join(part[:1].upper() + part[1:] for part in role.split("_"))


def build_nvim(palette):
    lines = [f"-- {HEADER}", "", "---@class PaletteColors", "return {"]
    for name, variant in palette["variants"].items():
        lines.append(f"    -- {name}: {variant['description']}")
        for role, color in variant["colors"].items():
            lines.append(f'    {camel(name, role)} = "{color}",')
        lines.append("")
    lines[-1] = "}"
    return {"lua/ukiyo/palette.lua": "\n".join(lines) + "\n"}


